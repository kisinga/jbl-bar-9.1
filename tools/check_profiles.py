#!/usr/bin/env python3
"""Check profile/runtime drift; --write refreshes generated Go identities only.

Pinned shell payloads are checked, never regenerated or relaxed. A profile edit
cannot silently make a historical installer accept another firmware.
"""
import argparse
import re
import subprocess

from repo_layout import BAR91, REMOTE, bar91_profile


def remote_source(profile):
    source = ["// Code generated by tools/check_profiles.py --write; DO NOT EDIT.",
              "// Source: models/bar91/profile.json. Runtime eligibility remains firmware-pinned.",
              "package main", "",
              f'const firmwareHash = "{profile["executables"]["bdpprog"]}"',
              f'const cliHash = "{profile["executables"]["cli"]}"', ""]
    for variable, helper in (("bluetoothLibraries", "bluetooth"), ("eqParserDependencies", "eq_parser")):
        source.append(f"var {variable} = map[string]string{{")
        source += [f'\t"{path}": "{digest}",' for path, digest in sorted(profile["native_helpers"][helper].items())]
        source += ["}", ""]
    return subprocess.check_output(["gofmt"], input=("\n".join(source) + "\n").encode())


def check_shell(profile):
    expected = profile["executables"]
    for name in ("run.sh", "once.sh", "controller.sh", "helper.sh"):
        text = (BAR91 / "smart-mode/JBLInstall/payload" / name).read_text()
        for variable, key in (("EXPECTED_BDP", "bdpprog"), ("EXPECTED_CLI", "cli")):
            found = re.search(rf"^{variable}=([0-9a-f]{{64}})$", text, re.M)
            if variable == "EXPECTED_CLI" and name == "run.sh":
                continue
            if found is None or found.group(1) != expected[key]:
                raise ValueError(f"Profile disagrees with pinned {name}:{variable}")
    preflight = (BAR91 / "usb/preflight.sh").read_text()
    checked = re.findall(r'\[ "\$\{hash%% \*\}" = ([0-9a-f]{64}) \]', preflight)
    if checked != [expected["bdpprog"], expected["cli"]]:
        raise ValueError("USB preflight disagrees with firmware profile")
    native = (REMOTE / "eq_native.go").read_text()
    hdsp = re.search(r'const eqHDSPHash = "([0-9a-f]{64})"', native)
    if hdsp is None or hdsp.group(1) != profile["native_helpers"]["eq_parser"]["/usr/lib/libhdsp.so"]:
        raise ValueError("Native EQ guard disagrees with parser profile")


def check(write=False):
    profile = bar91_profile()
    check_shell(profile)
    generated = REMOTE / "profile_bar91_generated.go"
    expected = remote_source(profile)
    if write:
        generated.write_bytes(expected)
    elif not generated.is_file() or generated.read_bytes() != expected:
        raise ValueError("Generated remote profile is stale; run python3 tools/check_profiles.py --write")
    return profile["id"]


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    print("Firmware profile checked:", check(args.write))
